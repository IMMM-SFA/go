######================Objective function=============########

def SysCost(model):
    fixed = sum(self.model.no_load[j]*self.model.on[j,i] for i in self.model.hh_periods for j in self.model.Dispatchable)
    starts = sum(self.model.st_cost[j]*self.model.switch[j,i] for i in self.model.hh_periods for j in self.model.Dispatchable)
    coal = sum(self.model.mwh[j,i]*(self.model.heat_rate[j]*2 + self.model.var_om[j]) for i in self.model.hh_periods for j in self.model.Coal)  
    oil = sum(self.model.mwh[j,i]*(self.model.heat_rate[j]*10 + self.model.var_om[j]) for i in self.model.hh_periods for j in self.model.Oil)
    gas = sum(self.model.mwh[j,i]*(self.model.heat_rate[j]*4.5 + self.model.var_om[j]) for i in self.model.hh_periods for j in self.model.Gas)
    slack = sum(self.model.S[z,i]*100000 for i in self.model.hh_periods for z in self.model.buses)
    
    return coal + oil + gas + slack + fixed + starts 

self.model.SystemCost = Objective(rule=SysCost, sense=minimize)



