#####=========== Capacity Constraints ============##########
# Constraints for Max & Min Capacity of dispatchable resources
def MaxC(model,j,i):
    return self.model.mwh[j,i]  <= self.model.on[j,i] * self.model.maxcap[j] 
self.model.MaxCap= Constraint(self.model.Dispatchable,self.model.hh_periods,rule=MaxC)


def MinC(model,j,i):
    return self.model.mwh[j,i] >= self.model.on[j,i] * self.model.mincap[j]
self.model.MinCap= Constraint(self.model.Dispatchable,self.model.hh_periods,rule=MinC)


#Max capacity constraints on domestic hydropower 
def HydroC(model,j,i):
    daily = sum(self.model.mwh[j,i] for i in self.model.hh_periods)
    return  daily <= self.model.HorizonHydro[j]    
self.model.HydroConstraint= Constraint(self.model.Hydro,self.model.hh_periods,rule=HydroC)


#Max capacity constraints on solar
def SolarC(model,j,i): 
    return  self.model.mwh[j,i] <= self.model.HorizonSolar[j,i]    
self.model.SolarConstraint= Constraint(self.model.Solar,self.model.hh_periods,rule=SolarC)

#Max capacity constraints on wind
def WindC(model,j,i): 
    return  self.model.mwh[j,i] <= self.model.HorizonWind[j,i]    
self.model.WindConstraint= Constraint(self.model.Wind,self.model.hh_periods,rule=WindC)


