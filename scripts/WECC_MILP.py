#####========== Logical Constraint =========#############
# Switch is 1 if unit is turned on in current period
def SwitchCon(model,j,i):
    return self.model.switch[j,i] >= 1 - self.model.on[j,i-1] - (1 - self.model.on[j,i])
self.model.SwitchConstraint = Constraint(self.model.Dispatchable,self.model.hh_periods,rule = SwitchCon)


######========== Up/Down Time Constraint =========#############
#Min Up time
def MinUp(model,j,i,k):
    if i > 0 and k > i and k < min(i+self.model.minup[j]-1,self.model.HorizonHours):
        return self.model.on[j,i] - self.model.on[j,i-1] <= self.model.on[j,k]
    else: 
        return Constraint.Skip
self.model.MinimumUp = Constraint(self.model.Thermal,self.model.HH_periods,self.model.HH_periods,rule=MinUp)

##Min Down time
def MinDown(model,j,i,k):
    if i > 0 and k > i and k < min(i+self.model.mindn[j]-1,self.model.HorizonHours):
        return self.model.on[j,i-1] - self.model.on[j,i] <= 1 - self.model.on[j,k]
    else:
        return Constraint.Skip
self.model.MinimumDown = Constraint(self.model.Thermal,self.model.HH_periods,self.model.HH_periods,rule=MinDown)


#####==========Ramp Rate Constraints =========#############
def Ramp1(model,j,i):
    a = self.model.mwh[j,i]
    b = self.model.mwh[j,i-1]
    return a - b <= self.model.ramp[j] 
self.model.RampCon1 = Constraint(self.model.Thermal,self.model.ramp_periods,rule=Ramp1)

def Ramp2(model,j,i):
    a = self.model.mwh[j,i]
    b = self.model.mwh[j,i-1]
    return b - a <= self.model.ramp[j] 
self.model.RampCon2 = Constraint(self.model.Thermal,self.model.ramp_periods,rule=Ramp2)


