def Nodal_Balance(model,z,i):
    power_flow = sum(self.model.Flow[l,i]*self.model.LinetoBusMap[l,z] for l in self.model.lines)   
    gen = sum(self.model.mwh[j,i]*self.model.BustoUnitMap[j,z] for j in self.model.Generators)    
    slack = self.model.S[z,i]
    must_run = self.model.Must[z]
    return gen + slack + must_run - power_flow == self.model.HorizonDemand[z,i] 
self.model.Node_Constraint = Constraint(self.model.buses,self.model.hh_periods,rule=Nodal_Balance)

def Flow_line(model,l,i):
    value = sum(self.model.Theta[z,i]*self.model.LinetoBusMap[l,z] for z in self.model.buses)
    return  100*value == self.model.Flow[l,i]*self.model.Reactance[l]
self.model.FlowL_Constraint = Constraint(self.model.lines,self.model.hh_periods,rule=Flow_line)

def Theta_bus(model,i):
        return self.model.Theta['MESA_CAL_20',i] == 0
self.model.ThetaB_Constraint = Constraint(self.model.hh_periods,rule=Theta_bus)

def FlowUP_line(model,l,i):
    return  self.model.Flow[l,i] <= self.model.FlowLim[l]
self.model.FlowU_Constraint = Constraint(self.model.lines,self.model.hh_periods,rule=FlowUP_line)

def FlowLow_line(model,l,i):
    return  -1*self.model.Flow[l,i] <= self.model.FlowLim[l]
self.model.FlowLL_Constraint = Constraint(self.model.lines,self.model.hh_periods,rule=FlowLow_line)

